from reportlab.pdfgen import canvas

class NumberedCanvas(canvas.Canvas):
    """Adds professional running headers and footers with total page numbers."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running Header on page 2+
        if self._pageNumber > 1:
            self.drawString(36, 756, "SOFTWARE ARCHITECTURE DRIFT DETECTOR — AUDIT REPORT")
            self.setStrokeColor(colors.HexColor("#CBD5E1"))
            self.setLineWidth(0.5)
            self.line(36, 750, 576, 750)

        # Running Footer on all pages
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(36, 45, 576, 45)

        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        self.drawString(36, 32, "Confidential — Generated by Software Architecture Drift Detector")
        self.drawRightString(576, 32, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()


class PdfReportGenerator:
    @staticmethod
    def generate_pdf(report_data: Dict[str, Any]) -> io.BytesIO:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=36,
            rightMargin=36,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()

        # Custom typography styles
        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=20,
            leading=24,
            textColor=colors.HexColor('#0F172A')
        )
        subtitle_style = ParagraphStyle(
            'DocSubtitle',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=11,
            leading=15,
            textColor=colors.HexColor('#475569')
        )
        h2_style = ParagraphStyle(
            'SectionH2',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=13,
            leading=17,
            textColor=colors.HexColor('#0F172A'),
            spaceBefore=14,
            spaceAfter=6
        )
        cell_bold = ParagraphStyle(
            'CellBold',
            parent=styles['Normal'],
            fontName='Helvetica-Bold',
            fontSize=9,
            leading=12,
            textColor=colors.HexColor('#1E293B')
        )
        cell_normal = ParagraphStyle(
            'CellNormal',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=8.5,
            leading=11.5,
            textColor=colors.HexColor('#334155')
        )
        code_style = ParagraphStyle(
            'CodeStyle',
            parent=styles['Normal'],
            fontName='Courier',
            fontSize=8,
            leading=10.5,
            textColor=colors.HexColor('#0F172A')
        )

        elements = []

        project = report_data.get("project", {})
        arch = report_data.get("architecture", {})
        scan = report_data.get("scan", {})
        findings = report_data.get("findings", [])

        # 1. Header Banner
        elements.append(Paragraph("Software Architecture Drift Detector", title_style))
        elements.append(Spacer(1, 3))
        elements.append(
            Paragraph("Executive Architecture Compliance & Drift Audit Report", subtitle_style)
        )
        elements.append(Spacer(1, 8))
        elements.append(
            HRFlowable(width="100%", thickness=2, color=colors.HexColor('#0F172A'), spaceBefore=2, spaceAfter=12)
        )

        # 2. Key Metadata & Scorecard Grid
        score = scan.get("compliance_percentage", 100.0)
        score_color = '#0D9488' if score >= 85 else ('#D97706' if score >= 60 else '#DC2626')

        score_html = f"<font size=24 color='{score_color}'><b>{score:.1f}%</b></font><br/><font size=8 color='#475569'>Compliance Score</font>"
        findings_html = f"<font size=20 color='#0F172A'><b>{scan.get('total_findings', 0)}</b></font><br/><font size=8 color='#475569'>Total Drift Findings</font>"
        modules_html = f"<font size=20 color='#0F172A'><b>{scan.get('modules_discovered', 0)}</b></font><br/><font size=8 color='#475569'>Modules Discovered</font>"
        deps_html = f"<font size=20 color='#0F172A'><b>{scan.get('dependencies_discovered', 0)}</b></font><br/><font size=8 color='#475569'>Dependencies Analyzed</font>"

        kpi_table_data = [
            [
                Paragraph(score_html, cell_normal),
                Paragraph(findings_html, cell_normal),
                Paragraph(modules_html, cell_normal),
                Paragraph(deps_html, cell_normal),
            ]
        ]
        kpi_table = Table(kpi_table_data, colWidths=[135, 135, 135, 135])
        kpi_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#E2E8F0')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('TOPPADDING', (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
        ]))
        elements.append(kpi_table)
        elements.append(Spacer(1, 10))

        # 3. Project & Architecture Information Table
        meta_data = [
            [
                Paragraph("<b>Target Project:</b>", cell_normal),
                Paragraph(project.get("name") or "Unknown Project", cell_bold),
                Paragraph("<b>Scan Status:</b>", cell_normal),
                Paragraph(f"<font color='#0D9488'><b>{scan.get('status', 'Completed').upper()}</b></font>", cell_normal)
            ],
            [
                Paragraph("<b>Primary Language:</b>", cell_normal),
                Paragraph(str(project.get("primary_language") or "Python").capitalize(), cell_normal),
                Paragraph("<b>Execution Duration:</b>", cell_normal),
                Paragraph(f"{scan.get('duration_ms', 0)} ms", cell_normal)
            ],
            [
                Paragraph("<b>Architecture Model:</b>", cell_normal),
                Paragraph(f"{arch.get('name') or 'Standard Policy'} (v{arch.get('version', 1)})", cell_normal),
                Paragraph("<b>Report Generated:</b>", cell_normal),
                Paragraph(datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"), cell_normal)
            ],
            [
                Paragraph("<b>Scan Run ID:</b>", cell_normal),
                Paragraph(scan.get("id", "N/A"), code_style),
                Paragraph("<b>Files Analyzed:</b>", cell_normal),
                Paragraph(str(scan.get("files_analyzed", 0)), cell_normal)
            ]
        ]
        meta_table = Table(meta_data, colWidths=[100, 170, 110, 160])
        meta_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.white),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#F1F5F9')),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(meta_table)

        # 4. Severity Distribution Breakdown
        elements.append(Paragraph("Severity Distribution Breakdown", h2_style))
        crit = scan.get("critical_findings", 0)
        high = scan.get("high_findings", 0)
        med = scan.get("medium_findings", 0)
        low = scan.get("low_findings", 0)

        dist_data = [
            [
                Paragraph("<font color='#DC2626'><b>Critical</b></font>", cell_normal),
                Paragraph("<font color='#EA580C'><b>High</b></font>", cell_normal),
                Paragraph("<font color='#D97706'><b>Medium</b></font>", cell_normal),
                Paragraph("<font color='#2563EB'><b>Low</b></font>", cell_normal),
            ],
            [
                Paragraph(f"<font size=12 color='#DC2626'><b>{crit}</b></font>", cell_normal),
                Paragraph(f"<font size=12 color='#EA580C'><b>{high}</b></font>", cell_normal),
                Paragraph(f"<font size=12 color='#D97706'><b>{med}</b></font>", cell_normal),
                Paragraph(f"<font size=12 color='#2563EB'><b>{low}</b></font>", cell_normal),
            ]
        ]
        dist_table = Table(dist_data, colWidths=[135, 135, 135, 135])
        dist_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (0, 1), colors.HexColor('#FEF2F2')),
            ('BACKGROUND', (1, 0), (1, 1), colors.HexColor('#FFF7ED')),
            ('BACKGROUND', (2, 0), (2, 1), colors.HexColor('#FFFBEB')),
            ('BACKGROUND', (3, 0), (3, 1), colors.HexColor('#EFF6FF')),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(dist_table)
        elements.append(Spacer(1, 10))

        # 5. Detailed Findings Section
        elements.append(Paragraph(f"Detailed Architectural Drift Findings ({len(findings)})", h2_style))

        if not findings:
            clean_msg = [
                [
                    Paragraph(
                        "<b>✔ Architecture Fully Compliant:</b> No component boundary violations, illegal upward layer calls, or circular dependencies were detected during this scan.",
                        cell_bold
                    )
                ]
            ]
            clean_table = Table(clean_msg, colWidths=[540])
            clean_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F0FDF4')),
                ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#86EFAC')),
                ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor('#166534')),
                ('PADDING', (0, 0), (-1, -1), 10),
            ]))
            elements.append(clean_table)
        else:
            sev_colors = {
                'critical': '#DC2626',
                'high': '#EA580C',
                'medium': '#D97706',
                'low': '#2563EB',
            }

            for idx, f in enumerate(findings, start=1):
                sev = f.get("severity", "medium").lower()
                badge_color = sev_colors.get(sev, '#475569')

                card_data = [
                    # Row 1: Header / Title
                    [
                        Paragraph(
                            f"<b>#{idx}</b> <font color='{badge_color}'><b>[{sev.upper()}]</b></font> <b>{f.get('title', 'Architecture Violation')}</b>",
                            cell_bold
                        ),
                        Paragraph(f"<b>Rule:</b> {f.get('rule_id', 'N/A')}", cell_normal)
                    ],
                    # Row 2: Location and status
                    [
                        Paragraph(
                            f"<b>File:</b> {f.get('file_path', 'N/A')}:{f.get('line_number', '?')}",
                            cell_normal
                        ),
                        Paragraph(f"<b>Status:</b> {f.get('status', 'open').upper()}", cell_normal)
                    ],
                    # Row 3: Component trace
                    [
                        Paragraph(
                            f"<b>Dependency:</b> {f.get('source_component', 'unmapped')} ➔ {f.get('target_component', 'unmapped')}",
                            cell_normal
                        ),
                        Paragraph(
                            f"<b>Modules:</b> {f.get('source_module', '?')} ➔ {f.get('target_module', '?')}",
                            cell_normal
                        )
                    ],
                    # Row 4: Evidence & Explanation
                    [
                        Paragraph(
                            f"<b>Explanation:</b> {f.get('explanation', '')}<br/>"
                            f"<b>Evidence:</b> <code>{f.get('evidence', 'None')}</code>",
                            cell_normal
                        ),
                        Paragraph(
                            f"<b>Remediation:</b><br/>{f.get('remediation', 'Refactor imports to follow architecture boundary guidelines.')}",
                            cell_normal
                        )
                    ]
                ]

                card_table = Table(card_data, colWidths=[340, 200])
                card_table.setStyle(TableStyle([
                    ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#F8FAFC')),
                    ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
                    ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#F1F5F9')),
                    ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                    ('TOPPADDING', (0, 0), (-1, -1), 4),
                    ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
                    ('LEFTPADDING', (0, 0), (-1, -1), 6),
                    ('RIGHTPADDING', (0, 0), (-1, -1), 6),
                ]))

                elements.append(KeepTogether([card_table, Spacer(1, 8)]))

        doc.build(elements, canvasmaker=NumberedCanvas)
        buffer.seek(0)
        return buffer
